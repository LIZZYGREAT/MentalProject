# 默认中性分
DEFAULT_SCORE = 5.0


# ---------------------------------------------------------------
# 2. 文本打分函数
# ---------------------------------------------------------------
def score_description(description: str) -> float:
    """
    根据 description 文本内容给出一个数值分 [1, 10]。

    规则：
        - 含有积极词汇 => 提高分值
        - 含有消极或压力相关词汇 => 降低分值
        - 若无匹配关键词或无描述 => 返回 DEFAULT_SCORE

    参数:
        description (str): 文本描述
    返回:
        score (float): 1–10 分之间的数值
    """
    if not description or not isinstance(description, str):
        return DEFAULT_SCORE

    desc = description.lower()  # 统一小写以兼容英文
    score = DEFAULT_SCORE

    # 累积分数
    for word, val in POSITIVE_WORDS.items():
        if re.search(word, desc):
            score += val
    for word, val in NEGATIVE_WORDS.items():
        if re.search(word, desc):
            score += val
    for word, val in EXAM_WORDS.items():
        if re.search(word, desc):
            score += val

    # 限制范围 [1, 10]
    return max(1.0, min(10.0, score))


# ---------------------------------------------------------------
# 3. 分数 → 喜好因子 F_like
# ---------------------------------------------------------------
def convert_score_to_Flike(score: float) -> float:
    """
    将 1–10 分映射到 [-1, 1]，用于压力建模。

    例如：
        1分  → -1.0 （极不喜欢）
        5分  →  0.0 （中性）
        10分 → +1.0 （非常喜欢）

    参数:
        score (float): 1–10 分
    返回:
        F_like (float): [-1, 1]
    """
    score = max(1.0, min(10.0, score))
    return round((score - 5.0) / 5.0, 3)


